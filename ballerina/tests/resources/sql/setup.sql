CREATE PROCEDURE BALTEST.ECHO_TYPES (
    IN I_I INT, OUT O_I INT, IN I_DEC DECIMAL(10, 2), OUT O_DEC DECIMAL(10, 2), IN I_DF DECFLOAT(34), OUT O_DF DECFLOAT(34),
    IN I_V VARCHAR(50), OUT O_V VARCHAR(50), IN I_G VARGRAPHIC(20), OUT O_G VARGRAPHIC(20),
    IN I_B VARBINARY(16), OUT O_B VARBINARY(16), IN I_DT DATE, OUT O_DT DATE, IN I_TM TIME, OUT O_TM TIME,
    IN I_TS TIMESTAMP(9), OUT O_TS TIMESTAMP(9), IN I_BOOL BOOLEAN, OUT O_BOOL BOOLEAN, IN I_X XML, OUT O_X XML)
    LANGUAGE SQL
BEGIN
    SET O_I = I_I; SET O_DEC = I_DEC; SET O_DF = I_DF; SET O_V = I_V; SET O_G = I_G; SET O_B = I_B;
    SET O_DT = I_DT; SET O_TM = I_TM; SET O_TS = I_TS; SET O_BOOL = I_BOOL; SET O_X = I_X;
END
@
CREATE PROCEDURE BALTEST.ECHO_INOUT (INOUT P_V VARCHAR(50), INOUT P_N DECIMAL(10, 2), INOUT P_TS TIMESTAMP, INOUT P_X XML)
    LANGUAGE SQL
BEGIN
    SET P_V = COALESCE(P_V, 'was null') || '!';
    SET P_N = COALESCE(P_N, 0) + 1;
    SET P_TS = COALESCE(P_TS, TIMESTAMP('2000-01-01-00.00.00')) + 1 DAY;
    SET P_X = COALESCE(P_X, XMLPARSE(DOCUMENT '<null/>'));
END
@
CREATE PROCEDURE BALTEST.BOOL_OUT (IN P_IN BOOLEAN, OUT P_SAME BOOLEAN, OUT P_NOT BOOLEAN, OUT P_NULL BOOLEAN)
    LANGUAGE SQL
BEGIN
    SET P_SAME = P_IN; SET P_NOT = NOT P_IN; SET P_NULL = NULL;
END
@
CREATE PROCEDURE BALTEST.DECFLOAT_OUT (OUT P_NAN DECFLOAT(34), OUT P_INF DECFLOAT(34), OUT P_BIG DECFLOAT(34))

END
@
CREATE PROCEDURE BALTEST.COUNT_NAME (IN P_V VARCHAR(50), OUT P_COUNT INT)
    LANGUAGE SQL
BEGIN
    SELECT COUNT(*) INTO P_COUNT FROM BALTEST.STR_T WHERE V = P_V;
END

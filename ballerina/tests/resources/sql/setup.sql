CREATE PROCEDURE BALTEST.GET_EMPLOYEES (IN P_DEPT CHAR(3), OUT P_COUNT INT)
    DYNAMIC RESULT SETS 1
    LANGUAGE SQL
BEGIN
    DECLARE C1 CURSOR WITH RETURN FOR
        SELECT ID, NAME, SALARY FROM BALTEST.EMPLOYEE WHERE DEPT = P_DEPT ORDER BY ID;
    SELECT COUNT(*) INTO P_COUNT FROM BALTEST.EMPLOYEE WHERE DEPT = P_DEPT;
    OPEN C1;
END
@
CREATE PROCEDURE BALTEST.SCALE_VALUE (INOUT P_VALUE DECIMAL(12, 2), IN P_FACTOR INT, OUT P_LABEL VARCHAR(30))
    LANGUAGE SQL
BEGIN
    SET P_VALUE = P_VALUE * P_FACTOR;
    SET P_LABEL = 'scaled by ' || VARCHAR(P_FACTOR);
END
@
CREATE PROCEDURE BALTEST.TWO_RESULT_SETS ()
    DYNAMIC RESULT SETS 2
    LANGUAGE SQL
BEGIN
    DECLARE C1 CURSOR WITH RETURN FOR SELECT ID, NAME FROM BALTEST.EMPLOYEE WHERE DEPT = 'ENG' ORDER BY ID;
    DECLARE C2 CURSOR WITH RETURN FOR SELECT DEPT, COUNT(*) AS TOTAL FROM BALTEST.EMPLOYEE GROUP BY DEPT ORDER BY DEPT;
    OPEN C1;
    OPEN C2;
END

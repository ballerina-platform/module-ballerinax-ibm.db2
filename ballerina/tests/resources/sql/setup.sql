CREATE PROCEDURE BALTEST.MIXED_RESULTS (IN P_NAME VARCHAR(50), OUT P_COUNT INT)
    DYNAMIC RESULT SETS 2
    LANGUAGE SQL
BEGIN
    DECLARE C1 CURSOR WITH RETURN FOR SELECT ID, NAME FROM BALTEST.EMPLOYEE WHERE DEPT = 'ENG' ORDER BY ID;
    DECLARE C2 CURSOR WITH RETURN FOR SELECT COUNT(*) AS TOTAL FROM BALTEST.EXEC_T;
    INSERT INTO BALTEST.EXEC_T (NAME) VALUES (P_NAME);
    SELECT COUNT(*) INTO P_COUNT FROM BALTEST.EXEC_T;
    OPEN C1;
    OPEN C2;
END
@
CREATE PROCEDURE BALTEST.RAISE_ERR (IN P_MSG VARCHAR(70))
    LANGUAGE SQL
BEGIN
